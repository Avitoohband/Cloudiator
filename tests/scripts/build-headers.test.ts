import { afterEach, describe, expect, it } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { connectOrigin, contentSecurityPolicy, headersFile } from '../../scripts/build-headers.mjs';

// Task 23.6, plan Decision 7: a generated `_headers` for Cloudflare Pages, built from the production Supabase URL, and plan
// Decision 2: the hand-written art gallery is not part of a production export. The policy strings are pinned literally here,
// so widening any directive is a visible test change.

const POLICY = "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; "
  + "connect-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'; form-action 'self'";
const PROJECT = 'https://abcdefghijklmnop.supabase.co';

const directories: string[] = [];
afterEach(() => { for (const directory of directories.splice(0)) rmSync(directory, { recursive: true, force: true }); });
/** A minimal exported site with the art gallery the public folder copies into it. */
function exportedSite() {
  const directory = mkdtempSync(join(tmpdir(), 'cloudiator-headers-'));
  directories.push(directory);
  mkdirSync(join(directory, 'assets'), { recursive: true });
  writeFileSync(join(directory, 'index.html'), '<main>Cloudiator</main>');
  writeFileSync(join(directory, 'assets/gallery.html'), '<script>gallery()</script>');
  writeFileSync(join(directory, 'assets/manifest.json'), '{}');
  return directory;
}
function finish(directory: string, env: Record<string, string | undefined> = {}) {
  const childEnv: Record<string, string | undefined> = { ...process.env, NEXT_PUBLIC_SUPABASE_URL: undefined, ...env };
  for (const key of Object.keys(childEnv)) if (childEnv[key] === undefined) delete childEnv[key];
  return spawnSync(process.execPath, [resolve('scripts/build-headers.mjs'), directory], { encoding: 'utf8', env: childEnv as NodeJS.ProcessEnv });
}

describe('the Decision 7 policy', () => {
  it('allows only the site itself to be connected to when the build has no Supabase URL', () => {
    expect(contentSecurityPolicy(null)).toBe(POLICY);
  });

  it('adds exactly the production project origin to connect-src', () => {
    expect(contentSecurityPolicy(PROJECT)).toBe(POLICY.replace("connect-src 'self'", `connect-src 'self' ${PROJECT}`));
  });

  it('writes the Cloudflare Pages rules: the policy and the three headers on every path, immutable caching for /_next/static/*', () => {
    expect(headersFile(PROJECT)).toBe([
      '# Generated by scripts/build-headers.mjs (Task 23.6, plan Decision 7). Rebuild instead of editing.',
      '/*',
      `  Content-Security-Policy: ${contentSecurityPolicy(PROJECT)}`,
      '  X-Content-Type-Options: nosniff',
      '  Referrer-Policy: strict-origin-when-cross-origin',
      '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
      '/_next/static/*',
      '  Cache-Control: public, max-age=31536000, immutable',
      '',
    ].join('\n'));
  });
});

describe('the connect-src origin', () => {
  it('takes the origin of a hosted project URL or a loopback development URL', () => {
    expect(connectOrigin(undefined)).toBeNull();
    expect(connectOrigin('')).toBeNull();
    expect(connectOrigin(PROJECT)).toBe(PROJECT);
    expect(connectOrigin(`${PROJECT}/`)).toBe(PROJECT);
    expect(connectOrigin('http://127.0.0.1:54321')).toBe('http://127.0.0.1:54321');
    expect(connectOrigin('http://localhost:54321')).toBe('http://localhost:54321');
  });

  it.each([
    'http://abcdefghijklmnop.supabase.co', 'https://evil.example', 'https://abcdefghijklmnop.supabase.co.evil.example',
    'https://user@abcdefghijklmnop.supabase.co', 'http://10.0.0.5:54321', 'javascript:alert(1)', 'not a url', 'https://*.supabase.co',
  ])('refuses %s', (url) => {
    expect(() => connectOrigin(url)).toThrow(/NEXT_PUBLIC_SUPABASE_URL/);
  });
});

describe('scripts/build-headers.mjs', () => {
  it('writes _headers and removes the development-only art gallery from the export', () => {
    const directory = exportedSite();
    const result = finish(directory, { NEXT_PUBLIC_SUPABASE_URL: PROJECT });
    expect(result.status, result.stderr).toBe(0);
    expect(readFileSync(join(directory, '_headers'), 'utf8')).toBe(headersFile(PROJECT));
    expect(existsSync(join(directory, 'assets/gallery.html'))).toBe(false);
    expect(existsSync(join(directory, 'assets/manifest.json'))).toBe(true);
    expect(result.stdout).toContain(`connect-src 'self' ${PROJECT}`);
  });

  it('writes the self-only policy for a build without a Supabase URL', () => {
    const directory = exportedSite();
    expect(finish(directory).status).toBe(0);
    expect(readFileSync(join(directory, '_headers'), 'utf8')).toBe(headersFile(null));
  });

  it('refuses an unexpected Supabase URL and writes nothing', () => {
    const directory = exportedSite();
    const result = finish(directory, { NEXT_PUBLIC_SUPABASE_URL: 'https://evil.example' });
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('NEXT_PUBLIC_SUPABASE_URL');
    expect(existsSync(join(directory, '_headers'))).toBe(false);
  });

  it('refuses a directory that is not an export', () => {
    const directory = mkdtempSync(join(tmpdir(), 'cloudiator-headers-'));
    directories.push(directory);
    const result = finish(directory);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('index.html');
  });

  it('runs after the production build', () => {
    const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
    expect(pkg.scripts.build).toBe('next build && node scripts/build-headers.mjs');
  });
});
