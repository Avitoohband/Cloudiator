/**
 * Finishes a production static export for its host, after `next build` (`npm run build`; Task 23.6):
 * - writes `<export>/_headers` for Cloudflare Pages (plan Decision 7): the Content-Security-Policy built from the build's
 *   `NEXT_PUBLIC_SUPABASE_URL`, `X-Content-Type-Options`, `Referrer-Policy`, a minimal `Permissions-Policy`, and immutable
 *   caching for `/_next/static/*`. `scripts/serve-static.mjs` applies the same file in the production browser gate.
 * - removes the hand-written art gallery (`assets/gallery.html`, a development tool with an inline script; plan Decision 2).
 *   It stays in `public/assets/` for `next dev` and any static server of the source tree.
 *
 * `'unsafe-inline'` scripts are a recorded exception: a static export cannot carry per-request nonces (Next.js
 * content-security-policy guide, "How nonces work"), and its framework scripts are inline.
 *
 * Usage: `node scripts/build-headers.mjs [export directory]`. The default is the directory next.config.ts exports to:
 * `.next/browser-test` when CLOUDIATOR_BROWSER_TEST=true, otherwise `out`. scripts/verify-static.mjs checks the result.
 *
 * Task 24.1 (plan Decision 12): the build environment is read the way `next build` reads it, with Next's own `@next/env`
 * (resolved through next, not a dependency of ours): the shell's variables first, then `.env.production.local`, `.env.local`, `.env.production` and `.env`
 * in the working directory, so `_headers` names the URL the bundle was built with. Only the loaded files' names are printed,
 * never a value. A production export without NEXT_PUBLIC_SUPABASE_URL fails (its policy would block every backend request);
 * only the browser-test export (CLOUDIATOR_BROWSER_TEST=true) is built without one and connects to the site alone.
 */
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// @next/env is Next's own dependency, not one of ours (no package.json entry): it is resolved from next's package, so this is
// always the copy `next build` itself uses (Task 24.1 fix round 1).
const nextRequire = createRequire(createRequire(import.meta.url).resolve('next/package.json'));
/** The resolved path of the @next/env this script loads (next's own). */
export const NEXT_ENV_PATH = nextRequire.resolve('@next/env');
const nextEnv = nextRequire(NEXT_ENV_PATH);

const HOSTED = /^[a-z0-9]+(?:-[a-z0-9]+)*\.supabase\.co$/;
const LOOPBACK = new Set(['127.0.0.1', 'localhost']);
export const PERMISSIONS_POLICY = 'camera=(), microphone=(), geolocation=(), payment=(), usb=()';
export const IMMUTABLE = 'public, max-age=31536000, immutable';
export const GALLERY = 'assets/gallery.html';

/**
 * The origin the browser may connect to besides the site: a hosted project (`https://<project>.supabase.co`) or, for a local
 * build, a loopback `http` URL (the same rule as src/lib/api/client.ts). No URL means none. Anything else is refused.
 * @param {string | undefined} url
 * @returns {string | null}
 */
export function connectOrigin(url) {
  if (!url) return null;
  const refuse = () => { throw new Error('NEXT_PUBLIC_SUPABASE_URL must be https://<project>.supabase.co, or a loopback http URL for a local build.'); };
  let parsed;
  try { parsed = new URL(url); } catch { return refuse(); }
  if (parsed.username || parsed.password) return refuse();
  if (parsed.protocol === 'https:' && HOSTED.test(parsed.hostname) && !parsed.port) return parsed.origin;
  if (parsed.protocol === 'http:' && LOOPBACK.has(parsed.hostname)) return parsed.origin;
  return refuse();
}

/**
 * Plan Decision 7's policy, with `connect-src` limited to the site and `origin`.
 * @param {string | null} origin
 */
export function contentSecurityPolicy(origin) {
  return [
    "default-src 'self'",
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    `connect-src 'self'${origin ? ` ${origin}` : ''}`,
    "object-src 'none'",
    "base-uri 'self'",
    "frame-ancestors 'none'",
    "form-action 'self'",
  ].join('; ');
}

/**
 * The `_headers` file (Cloudflare Pages: a path pattern, then its indented headers; every matching rule applies).
 * @param {string | null} origin
 */
export function headersFile(origin) {
  return [
    '# Generated by scripts/build-headers.mjs (Task 23.6, plan Decision 7). Rebuild instead of editing.',
    '/*',
    `  Content-Security-Policy: ${contentSecurityPolicy(origin)}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    `  Permissions-Policy: ${PERMISSIONS_POLICY}`,
    '/_next/static/*',
    `  Cache-Control: ${IMMUTABLE}`,
    '',
  ].join('\n');
}

/**
 * Reads a `_headers` file as Cloudflare Pages does: a path pattern line (`*` matches anything, `:name` one segment), then its
 * indented `Name: value` lines. Moved here from scripts/serve-static.mjs in Task 24.2, so the local export host and the
 * deployed checks (tests/browser/deployed-checks.ts) read the generated file the same way.
 * @param {string} text
 * @returns {{ pattern: RegExp, headers: [string, string][] }[]}
 */
export function parseHeaders(text) {
  /** @type {{ pattern: RegExp, headers: [string, string][] }[]} */
  const rules = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    if (!/^\s/.test(line)) {
      const pattern = line.trim().replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*').replace(/:\w+/g, '[^/]+');
      rules.push({ pattern: new RegExp(`^${pattern}$`), headers: [] });
      continue;
    }
    const at = line.indexOf(':');
    if (!rules.length || at < 0) throw new Error(`Malformed _headers line: ${line.trim()}`);
    rules[rules.length - 1].headers.push([line.slice(0, at).trim(), line.slice(at + 1).trim()]);
  }
  return rules;
}

/**
 * The headers `rules` give `pathname`: every rule whose pattern matches adds its headers, and a repeated header is joined with
 * ", " (Cloudflare Pages).
 * @param {{ pattern: RegExp, headers: [string, string][] }[]} rules
 * @param {string} pathname
 * @returns {Record<string, string>}
 */
export function headersFor(rules, pathname) {
  /** @type {Record<string, string>} */
  const headers = {};
  for (const rule of rules) {
    if (!rule.pattern.test(pathname)) continue;
    for (const [name, value] of rule.headers) headers[name] = headers[name] ? `${headers[name]}, ${value}` : value;
  }
  return headers;
}

/** The export directory next.config.ts writes for this environment. */
export const exportRoot = (env = process.env) => (env.CLOUDIATOR_BROWSER_TEST === 'true' ? '.next/browser-test' : 'out');

/**
 * Loads `dir`'s `.env*` files into process.env exactly as `next build` does (`loadEnvConfig(dir, false)`: production mode
 * unless NODE_ENV says otherwise; a variable already set wins). Returns the names of the files it loaded. A file that cannot
 * be read is reported by name only.
 * @param {string} [dir]
 */
export function loadBuildEnv(dir = process.cwd()) {
  const quiet = { info() {}, error(message) { console.error(String(message)); } };
  return nextEnv.loadEnvConfig(dir, false, quiet).loadedEnvFiles.map(file => file.path);
}

/**
 * Writes `_headers` into `root` and removes the art gallery. Refuses a directory without an exported `index.html`, an
 * unexpected Supabase URL, and a production export without one (Task 24.1), before writing or removing anything.
 * @param {string} root
 * @param {NodeJS.ProcessEnv} env
 */
export function finishExport(root, env = process.env) {
  if (!existsSync(join(root, 'index.html'))) throw new Error(`${root} is not a static export: index.html is missing. Run next build first.`);
  const origin = connectOrigin(env.NEXT_PUBLIC_SUPABASE_URL);
  if (!origin && env.CLOUDIATOR_BROWSER_TEST !== 'true') {
    throw new Error('NEXT_PUBLIC_SUPABASE_URL is not set: a production export must name its Supabase project in connect-src. Set it '
      + 'in the hosting build settings for a deploy, and set it in the shell for a local build: '
      + 'NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:54321 npm run build (a hosted project URL for a local deploy build). '
      + 'Any .env file that next build reads (.env.production.local, .env.local, .env.production, .env) is also read by the '
      + 'isolated browser-test build, whose bundle and _headers would then carry that URL. Keep the URL in the shell variable, '
      + 'out of those files. Only the browser-test export (CLOUDIATOR_BROWSER_TEST=true) is built without one.');
  }
  writeFileSync(join(root, '_headers'), headersFile(origin));
  const gallery = existsSync(join(root, GALLERY));
  if (gallery) rmSync(join(root, GALLERY));
  return { origin, galleryRemoved: gallery };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const files = loadBuildEnv();
    const root = resolve(process.argv[2] ?? exportRoot());
    const { origin, galleryRemoved } = finishExport(root);
    console.log(`Export finished: build environment from ${files.length ? files.join(', ') : 'the shell only'}; `
      + `_headers written (connect-src 'self'${origin ? ` ${origin}` : ''}); ${galleryRemoved ? 'art gallery removed' : 'no art gallery present'}.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
