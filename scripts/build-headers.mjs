/**
 * Finishes a production static export for its host, after `next build` (`npm run build`; Task 23.6):
 * - writes `<export>/_headers` for Cloudflare Pages (plan Decision 7): the Content-Security-Policy built from the build's
 *   `NEXT_PUBLIC_SUPABASE_URL`, `X-Content-Type-Options`, `Referrer-Policy`, a minimal `Permissions-Policy`, and immutable
 *   caching for `/_next/static/*`. `scripts/serve-static.mjs` applies the same file in the production browser gate.
 * - removes the hand-written art gallery (`assets/gallery.html`, a development tool with an inline script; plan Decision 2).
 *   It stays in `public/assets/` for `next dev` and any static server of the source tree.
 *
 * `'unsafe-inline'` scripts are a recorded exception: a static export cannot carry per-request nonces (Next.js
 * content-security-policy guide, "How nonces work"), and its framework scripts are inline.
 *
 * Usage: `node scripts/build-headers.mjs [export directory]`. The default is the directory next.config.ts exports to:
 * `.next/browser-test` when CLOUDIATOR_BROWSER_TEST=true, otherwise `out`. scripts/verify-static.mjs checks the result.
 */
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const HOSTED = /^[a-z0-9]+(?:-[a-z0-9]+)*\.supabase\.co$/;
const LOOPBACK = new Set(['127.0.0.1', 'localhost']);
export const PERMISSIONS_POLICY = 'camera=(), microphone=(), geolocation=(), payment=(), usb=()';
export const IMMUTABLE = 'public, max-age=31536000, immutable';
export const GALLERY = 'assets/gallery.html';

/**
 * The origin the browser may connect to besides the site: a hosted project (`https://<project>.supabase.co`) or, for a local
 * build, a loopback `http` URL (the same rule as src/lib/api/client.ts). No URL means none. Anything else is refused.
 * @param {string | undefined} url
 * @returns {string | null}
 */
export function connectOrigin(url) {
  if (!url) return null;
  const refuse = () => { throw new Error('NEXT_PUBLIC_SUPABASE_URL must be https://<project>.supabase.co, or a loopback http URL for a local build.'); };
  let parsed;
  try { parsed = new URL(url); } catch { return refuse(); }
  if (parsed.username || parsed.password) return refuse();
  if (parsed.protocol === 'https:' && HOSTED.test(parsed.hostname) && !parsed.port) return parsed.origin;
  if (parsed.protocol === 'http:' && LOOPBACK.has(parsed.hostname)) return parsed.origin;
  return refuse();
}

/**
 * Plan Decision 7's policy, with `connect-src` limited to the site and `origin`.
 * @param {string | null} origin
 */
export function contentSecurityPolicy(origin) {
  return [
    "default-src 'self'",
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    `connect-src 'self'${origin ? ` ${origin}` : ''}`,
    "object-src 'none'",
    "base-uri 'self'",
    "frame-ancestors 'none'",
    "form-action 'self'",
  ].join('; ');
}

/**
 * The `_headers` file (Cloudflare Pages: a path pattern, then its indented headers; every matching rule applies).
 * @param {string | null} origin
 */
export function headersFile(origin) {
  return [
    '# Generated by scripts/build-headers.mjs (Task 23.6, plan Decision 7). Rebuild instead of editing.',
    '/*',
    `  Content-Security-Policy: ${contentSecurityPolicy(origin)}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    `  Permissions-Policy: ${PERMISSIONS_POLICY}`,
    '/_next/static/*',
    `  Cache-Control: ${IMMUTABLE}`,
    '',
  ].join('\n');
}

/** The export directory next.config.ts writes for this environment. */
export const exportRoot = (env = process.env) => (env.CLOUDIATOR_BROWSER_TEST === 'true' ? '.next/browser-test' : 'out');

/**
 * Writes `_headers` into `root` and removes the art gallery. Refuses a directory without an exported `index.html` and an
 * unexpected Supabase URL, before writing anything.
 * @param {string} root
 * @param {NodeJS.ProcessEnv} env
 */
export function finishExport(root, env = process.env) {
  if (!existsSync(join(root, 'index.html'))) throw new Error(`${root} is not a static export: index.html is missing. Run next build first.`);
  const origin = connectOrigin(env.NEXT_PUBLIC_SUPABASE_URL);
  writeFileSync(join(root, '_headers'), headersFile(origin));
  const gallery = existsSync(join(root, GALLERY));
  if (gallery) rmSync(join(root, GALLERY));
  return { origin, galleryRemoved: gallery };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve(process.argv[2] ?? exportRoot());
  try {
    const { origin, galleryRemoved } = finishExport(root);
    console.log(`Export finished: _headers written (connect-src 'self'${origin ? ` ${origin}` : ''}); `
      + `${galleryRemoved ? 'art gallery removed' : 'no art gallery present'}.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
